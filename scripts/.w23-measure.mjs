import { register } from 'node:module';
import { pathToFileURL } from 'node:url';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
register('./ts-resolve-hook.mjs', pathToFileURL(join(ROOT, 'scripts/')));
const imp = (p) => import(pathToFileURL(join(ROOT, p)).href);
const routes = await imp('src/content/public-routes.ts');
const g = await imp('src/content/guides/index.ts');
const i = await imp('src/content/institutions.ts');
const p = await imp('src/content/professions.ts');
const gl = await imp('src/content/glossary.ts');
const d = await imp('src/content/dossiers/index.ts');
const s = await imp('src/content/sources.ts');
const rc = await imp('src/content/restricted-claims.ts');
const sc = await imp('src/content/scheduled-changes.ts');
const r = routes.PUBLIC_ROUTES;
console.log('TOTAL ROUTES:', r.length);
const byKind={}; for(const x of r) byKind[x.kind]=(byKind[x.kind]||0)+1;
console.log('BY KIND:', JSON.stringify(byKind));
const byTop={}; for(const x of r){const t='/'+(x.path.split('/')[1]||''); byTop[t]=(byTop[t]||0)+1;}
console.log('BY TOP:', Object.entries(byTop).sort((a,b)=>b[1]-a[1]).map(([k,v])=>`${k} ${v}`).join(' · '));
console.log('PUBLISHED_GUIDES:', g.PUBLISHED_GUIDES.length);
const bySec={}; for(const x of g.PUBLISHED_GUIDES) bySec[x.section]=(bySec[x.section]||0)+1;
console.log('GUIDES BY SECTION:', JSON.stringify(bySec));
const arr=(m)=>Object.entries(m).filter(([,v])=>Array.isArray(v)).map(([k,v])=>`${k}=${v.length}`).join(' | ');
console.log('INSTITUTIONS:', arr(i)); console.log('PROFESSIONS:', arr(p));
console.log('GLOSSARY:', arr(gl)); console.log('DOSSIERS:', arr(d));
console.log('SOURCES:', arr(s)); console.log('RESTRICTED:', arr(rc)); console.log('SCHEDULED:', arr(sc));
console.log('SCHEDULED IDS:', sc.SCHEDULED_CHANGES.map(x=>`${x.id}[${x.status}/${x.certainty}]`).join(' · '));
const byJ={}; for(const x of s.SOURCES){const k=x.jurisdiction??'unscoped'; byJ[k]=(byJ[k]||0)+1;}
console.log('SOURCES BY JURISDICTION:', Object.entries(byJ).sort((a,b)=>b[1]-a[1]).map(([k,v])=>`${k} ${v}`).join(' · '));
